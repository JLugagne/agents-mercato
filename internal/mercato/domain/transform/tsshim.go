package transform

import (
	"bytes"
	"encoding/json"
	"fmt"
	"math"
	"strings"

	"github.com/JLugagne/agents-mercato/internal/mercato/domain"
)

type shimArg struct {
	key  string
	expr string
}

type shimSpec struct {
	imports    []string
	hook       claudeHook
	toolNames  map[string]string
	toolEvent  bool
	promptText bool
	body       string
}

func shimJSString(s string) string {
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	if err := enc.Encode(s); err != nil {
		panic(err)
	}
	return strings.TrimSuffix(buf.String(), "\n")
}

func shimPascal(name string) string {
	var b strings.Builder
	for _, part := range strings.Split(name, "-") {
		if part == "" {
			continue
		}
		b.WriteString(strings.ToUpper(part[:1]))
		b.WriteString(part[1:])
	}
	return b.String()
}

func shimHookName(h claudeHook) string {
	if h.Name == "" {
		return "hook"
	}
	return h.Name
}

func shimMatcher(h claudeHook) string {
	m := strings.TrimSpace(h.Matcher)
	if m == "*" || m == ".*" {
		return ""
	}
	return m
}

func shimCall(indent, cwd string, args []shimArg) string {
	var b strings.Builder
	b.WriteString("runHandlers(" + cwd + ", {\n")
	for _, a := range args {
		b.WriteString(indent + "  " + a.key + ": " + a.expr + ",\n")
	}
	b.WriteString(indent + "})")
	return b.String()
}

func shimToolGuard(indent, toolExpr string, h claudeHook) string {
	s := indent + "const toolName = claudeToolName(" + toolExpr + ")\n"
	if shimMatcher(h) != "" {
		s += indent + "if (!matcher.test(toolName)) return\n"
	}
	return s
}

func renderShim(spec shimSpec) []byte {
	var b strings.Builder
	h := spec.hook
	fmt.Fprintf(&b, "// Generated by mct from the Claude Code hook %s (%s).\n", shimJSString(shimHookName(h)), h.Event)
	for _, imp := range spec.imports {
		b.WriteString(imp + "\n")
	}
	b.WriteString("import { spawnSync } from \"node:child_process\"\n\n")

	b.WriteString("const handlers: { command: string; timeout?: number }[] = [\n")
	for _, hd := range h.Handlers {
		if ms := int64(math.Round(hd.Timeout * 1000)); ms > 0 {
			fmt.Fprintf(&b, "  { command: %s, timeout: %d },\n", shimJSString(hd.Command), ms)
		} else {
			fmt.Fprintf(&b, "  { command: %s },\n", shimJSString(hd.Command))
		}
	}
	b.WriteString("]\n\n")

	if spec.toolEvent {
		if m := shimMatcher(h); m != "" {
			fmt.Fprintf(&b, "const matcher = new RegExp(%s)\n\n", shimJSString("^(?:"+m+")$"))
		}
		b.WriteString("const toolNames: Record<string, string> = {\n")
		for _, k := range sortedKeys(spec.toolNames) {
			fmt.Fprintf(&b, "  %s: %s,\n", shimJSString(k), shimJSString(spec.toolNames[k]))
		}
		b.WriteString("}\n\n")
	}

	b.WriteString(`function field(value: unknown, key: string): unknown {
  return value !== null && typeof value === "object" ? (value as Record<string, unknown>)[key] : undefined
}

`)
	if spec.toolEvent {
		b.WriteString(`function claudeToolName(tool: unknown): string {
  const name = String(tool ?? "")
  return toolNames[name] ?? name
}

`)
	}
	if spec.promptText {
		b.WriteString(`function promptText(parts: unknown): string {
  if (!Array.isArray(parts)) return ""
  return parts.map((part) => (field(part, "type") === "text" ? String(field(part, "text") ?? "") : "")).join("")
}

`)
	}
	b.WriteString(`function runHandlers(cwd: string, payload: Record<string, unknown>): string | undefined {
  let blocked: string | undefined
  for (const handler of handlers) {
    const result = spawnSync("sh", ["-c", handler.command], {
      cwd,
      input: JSON.stringify(payload),
      encoding: "utf8",
      timeout: handler.timeout,
    })
    if (result.status === 2 && blocked === undefined) {
      blocked = (result.stderr ?? "").trim() || "blocked by hook: " + handler.command
    }
  }
  return blocked
}

`)
	b.WriteString(spec.body)
	return []byte(b.String())
}

func shimHookResult(tool, path string, spec shimSpec, warnings []string) domain.TransformResult {
	return files(tool, []domain.OutputFile{{Path: path, Content: renderShim(spec)}}, warnings...)
}

func shimNoEvent(tool, event string) domain.TransformResult {
	return skipped(tool, fmt.Sprintf("no equivalent for hook event %q", event))
}

func shimMatcherIgnored(tool string, h claudeHook, toolEvent bool) []string {
	if toolEvent || shimMatcher(h) == "" {
		return nil
	}
	return []string{fmt.Sprintf("%s: hook matcher %q ignored for event %s", tool, h.Matcher, h.Event)}
}
